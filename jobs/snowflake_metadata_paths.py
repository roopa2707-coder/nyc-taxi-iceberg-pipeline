"""Part 4 helper: print the current Iceberg metadata file of each table and write
ready-to-run Snowflake SQL (snowflake/02_tables_generated.sql).

Snowflake reads the tables through an OBJECT_STORE catalog integration, which
needs the path of the latest metadata.json relative to the external volume's
STORAGE_BASE_URL (s3://<bucket>/warehouse/). Run this after every load, then
run the generated SQL in Snowflake to create or refresh the tables.

    python -m jobs.snowflake_metadata_paths
"""
from __future__ import annotations

from pipeline.config import REPO_ROOT, load_config
from pipeline.spark_session import build_spark

TABLES = ["trips_clean", "daily_zone_metrics", "trips_rejected"]


def main() -> None:
    cfg = load_config()
    spark = build_spark(cfg, "snowflake_metadata_paths")
    base = cfg.warehouse.rstrip("/") + "/"

    lines = [
        "-- GENERATED by jobs/snowflake_metadata_paths.py - re-generate after each load.",
        "USE ROLE taxi_role; USE DATABASE taxi_db; USE SCHEMA taxi;",
        "",
    ]
    for name in TABLES:
        latest = spark.sql(
            f"SELECT file FROM {cfg.table(name)}.metadata_log_entries ORDER BY timestamp DESC LIMIT 1"
        ).first()["file"]
        rel = latest.replace("s3a://", "s3://").split(base, 1)[-1]
        print(f"{name:<20} {rel}")
        lines += [
            f"-- first time: create the table",
            f"CREATE ICEBERG TABLE IF NOT EXISTS {name}",
            "  EXTERNAL_VOLUME = 'taxi_iceberg_vol'",
            "  CATALOG = 'taxi_objstore_cat'",
            f"  METADATA_FILE_PATH = '{rel}';",
            f"-- every later load: point it at the newest metadata file",
            f"ALTER ICEBERG TABLE {name} REFRESH '{rel}';",
            "",
        ]

    out = REPO_ROOT / "snowflake" / "02_tables_generated.sql"
    out.write_text("\n".join(lines))
    print(f"\nSnowflake SQL written to {out}")
    spark.stop()


if __name__ == "__main__":
    main()
